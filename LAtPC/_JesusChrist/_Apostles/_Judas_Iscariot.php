<!-- Apostle Judas Iscariot
The Shadow Among the Twelve
“Did I not choose you, the Twelve? And yet one of you is a devil.” John 6:70
Jesus spoke these words long before the night of betrayal. Long before the kiss in the garden. Long before silver clinked in a priest’s hand.
Judas was not an outsider. He was chosen. He walked with Jesus. He saw the miracles. He heard the teachings. He shared the bread.
To understand Judas, we must begin where the story truly begins — not with betrayal, but with calling.
Act I — The Calling and the Good Intentions
Judas the Chosen Disciple
Judas Iscariot was selected by Jesus Himself to be one of the Twelve. His name appears in every list of the apostles. He was not a stranger to the group — he was part of the inner circle that traveled, ate, and ministered together.
Name, Identity, and Background
“Iscariot” likely means “man of Kerioth,” a town in Judea. If so, Judas was the only Judean among Galileans — different accent, different customs, different expectations. He carried the weight of being the outsider, the one from the south, the one closest to the religious center of Israel.
Role and Responsibility
Judas kept the money bag. He handled donations, provisions, and financial planning. This role required trust. The others believed he was capable, organized, and reliable.
Witness to the Ministry
Judas saw:
    • the blind receive sight
    • the lame walk
    • the dead raised
    • storms calmed
    • demons cast out
He heard:
    • the Sermon on the Mount
    • the parables
    • the warnings
    • the promises
He was sent out with authority, just like the others. He preached. He healed. He cast out unclean spirits.
Judas began as a disciple with purpose, hope, and expectation.
Act II — The Descent and the Betrayal
The Growing Divide
Something changed. Not suddenly, but slowly — like a rope fraying strand by strand.
Judas watched Jesus refuse political power. He watched Him speak of suffering. He watched Him welcome sinners and rebuke religious leaders. He watched Him praise costly devotion instead of financial prudence.
The moment with the perfume — the fragrance filling the room — exposed the tension. Judas objected. Jesus corrected him. The divide widened.
The Decision
Judas went to the chief priests. He asked what they would give him. They counted out thirty pieces of silver — the price of a slave.
Judas accepted.
The Night of Shadows
At the table, Jesus washed Judas’s feet. He dipped bread and handed it to him. He said, “What you are about to do, do quickly.”
Judas left. It was night.
The Garden
Judas arrived with lanterns, torches, and soldiers. He approached Jesus. He greeted Him with a kiss — a sign of friendship turned into a signal of betrayal.
Jesus said, “Friend, do what you came to do.”
And the Son of Man was handed over.
Act III — The Ruin and the Aftermath
The Weight of the Choice
When Judas saw that Jesus was condemned, remorse struck him. He returned the silver. He confessed, “I have sinned; I have betrayed innocent blood.”
The priests answered, “What is that to us?”
The silver clattered on the temple floor.
The End of Judas
Alone. Rejected by the leaders he served. Separated from the disciples he once walked with. Unable to undo what had been done.
Judas ended his life in despair.
The field purchased with his returned silver became known as the Field of Blood.
The Vacancy
The Twelve were now eleven. A seat was empty. A witness was missing. A story had broken.
The community gathered. They prayed. They sought restoration.
The tragedy of Judas created the space where Matthias would later stand — not as a replacement of worth, but as a sign that God restores what human choices shatter.
