<!-- Saint James (Son of Zebedee)
James (Ἰάκωβος) bar Zebedee: A Galilean Fisherman
(Parallel to "Simon bar Jonah: A Galilean Fisherman")
Name, Identity, and Social Position
    • Hebrew name "Jacob" (Ἰάκωβος), rendered "James" in English
    • Son of Zebedee, elder brother of John the Apostle
    • From Bethsaida/Capernaum region, part of the Galilean fishing economy
    • Distinguished from James son of Alphaeus ("James the Less") and James the brother of Jesus
Family Structure & Responsibilities
    • Father Zebedee ran a fishing business substantial enough to employ hired servants (Mark 1:20)
    • Mother possibly Salome, traditionally identified as present at the crucifixion and tomb
    • A family of relative means compared to Peter and Andrew's household
    • Close working partnership with brother John
The Fishing Trade: Daily Reality
    • Business partners with Peter and Andrew (Luke 5:10)
    • Mending nets alongside his father when called by Jesus
    • Evidence of a family enterprise with employees, boats, and greater economic standing
Religious Life
    • Jewish upbringing and covenant expectation
    • Family investment in messianic hope, reflected later in his mother's request for status
Political Awareness
    • Life under Roman occupation and Herodian rule in Galilee
    • Ambition and expectation tied to popular hopes for a political-messianic kingdom
Reputation in the Community
    • Known, along with John, for intensity — nicknamed by Jesus "Boanerges," "Sons of Thunder" (Mark 3:17)
    • Bold, forceful temperament noted repeatedly in the Gospels
    • Part of Jesus's innermost circle of three, alongside Peter and John

James the Called
(Parallel to "The Day the Nets Were Full")
    • Called at the shore alongside John, leaving Zebedee in the boat with the hired men
    • Immediate, decisive response — no recorded hesitation
    • Entry into the inner circle of three from the earliest days of ministry

James's Journey
(Parallel to "Cephas's Journey": Walking on Water, Transfiguration, Denial/Restoration)
    • Present at the raising of Jairus's daughter — one of only three disciples allowed in (Mark 5:37)
    • Witness to the Transfiguration on the mountain (Matthew 17:1-9)
    • Present in Gethsemane during the agony in the garden, among the three closest to Jesus
    • The request through his mother for seats at Jesus's right and left hand (Matthew 20:20-23)
    • Rebuked with John for wanting to call down fire on a Samaritan village (Luke 9:54-55) — the "Sons of Thunder" moment
    • Jesus's response: a call to servant leadership rather than worldly power ("whoever wants to be great among you must be your servant")

James the Apostle of the Early Church
(Parallel to Peter's leadership: Pentecost, Miracles, Imprisonment, Council)
Holy Spirit Praxis
    • Presence at Pentecost among the Twelve
    • Participation in the earliest Jerusalem church's witness
Ministry and Presence
    • Continued closeness to Peter and John in Jerusalem's leadership circle
    • Brief window of recorded activity compared to Peter and Paul — his ministry is cut short early in Acts
Imprisonment and Martyrdom (in place of "The Council of Jerusalem")
    • Arrested by Herod Agrippa I in a wave of persecution against the church (Acts 12:1-2)
    • The first apostle martyred, and the only apostolic death recorded in Scripture itself
    • Executed by the sword — a swift, undramatic account that underscores the cost of early discipleship
    • Occurred before the Council of Jerusalem (c. AD 49), meaning James did not live to see it — worth flagging as a structural difference from Peter and Paul's outlines

James's Writings
(Parallel to "Peter's Writings" / "Paul's Writings")
    • No canonical writings attributed to James son of Zebedee
    • Important distinction: the Epistle of James in the New Testament is traditionally attributed to James the brother of Jesus (or James son of Alphaeus), not James son of Zebedee
    • Apocryphal and legendary texts associated with his later Spanish tradition (see below), of limited historical reliability
    • His legacy rests on action and witness recorded by others, not his own writing

The Final Journey
(Parallel to Peter's and Paul's Final Journeys)
What the Bible Tells Us
    • Scripture records his death directly and briefly — no trial narrative, no voyage, no final letters
    • The account closes almost as soon as it opens (Acts 12:1-2)
James's Ministry in Spain (Post-Biblical Tradition)
    • Later Iberian tradition holds that James preached in Spain before returning to Judea
    • Legend of the apparition of the Virgin Mary at Zaragoza (Our Lady of the Pillar)
    • Historically contested — a tradition that develops centuries after his death, unlike the earlier-attested traditions around Peter and Paul in Rome
James's Martyrdom
    • Beheaded under Herod Agrippa I in Jerusalem, c. AD 44
    • The most abrupt and least detailed martyrdom account among the apostles
    • Legend of his body's translation to Santiago de Compostela, Spain

James's Legacy
(Parallel to "Peter's Legacy" / "Paul's Legacy")
    • Santiago de Compostela becomes one of Christendom's great pilgrimage sites (Camino de Santiago)
    • Patron saint of Spain ("Santiago")
    • The first apostolic martyr — a marker of the church's earliest cost of discipleship
    • Model of transformed ambition: from seeking thrones to accepting the cup of suffering Jesus foretold (Matthew 20:22-23)
    • Enduring symbol of zeal refined into sacrificial faithfulness -->