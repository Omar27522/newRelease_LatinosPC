                    still afraid of Saul because they remembered how he had hurt Christians. But Barnabas listened to Saul and believed that Jesus had truly changed his heart. He took
                    Saul to the apostles and told them what had happened to him. Barnabas showed courage by standing beside Saul when others were afraid. He believed that God could change
                    anyone, even someone who had done terrible things. Barnabas helped the believers of Jesus see Saul as no longer their enemy. He was now a follower of Jesus and wanted to serve. </p>
