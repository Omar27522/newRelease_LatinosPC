              <p class="p_indent">On his very first long journey, Paul traveled with his friend Barnabas to tell people about Jesus. They sailed across the sea, walked along sun-baked roads, and
                crossed hills and mountains to reach towns they had never visited before. In some places, the journey was probably hot, tiring, and difficult, but Paul and Barnabas kept going
                because they truthfully believed God had sent them to share the good news about Jesus. <span class="indent">Whenever they arrived in a new town, Paul would often begin by visiting the local synagogue, a place
                where Jewish people gathered to worship God and read the Scriptures.</span></p>
                <p style="font-size:1.2rem;">Paul already knew those Scriptures very well, and he showed the people how they pointed to Jesus. After
                speaking there, Paul and Barnabas also shared the message with Gentiles—people who were not Jewish—who wanted to hear about Jesus.</p>
              <p class="p_indent">Not everyone believed Barnabas and Paul, but many people did. Some people heard about Jesus for the first time and decided to follow Him. These new believers began meeting
                together, learning about Jesus, praying, and helping one another. They became new <strong>church families</strong>—not just new buildings, but groups of people who loved Jesus
                and loved one another.</p>
              <p style="font-size:1.2rem;">As Paul and Barnabas continued from town to town, the message about Jesus spread farther and farther. Their journey was only beginning, but God was using them
                to help build new communities of believers in places that had never heard the good news before.</p>
