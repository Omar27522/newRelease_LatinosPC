                time, these groups were often separated from each other.
            <br />Jesus' death on the cross opened the way for believing all Jews and Gentiles could become part of God's family. Paul understood that God's plan was bigger
                than he had first imagined. God wanted people from every nation to hear the good news about Jesus. This new understanding became very important in Paul's life. God was
