            <h3>Saul’s Opposition to “The Way”</h3>
            <p>
                The earliest Christians referred to their movement as “<strong>The Way</strong>,”
                a path centered on Jesus as the
                <a href="https://www.foi.org/2021/04/01/the-messiah-who-was-israel-expecting/#:~:text=Jewish%20expectations%20of%20the%20Messiah%20in%20the%20time%20of%20Jesus%20focused%20on%20the%20coming%20of%20a%20conquering%20king."
                    title="The Messiah: Who Was Israel Expecting?">
                    fulfillment of Israel’s hopes</a>. Saul saw this new teaching as dangerous.<br />
                Saul was <b>“breathing out threats and slaughter” against the disciples of the Lord.</b>
                He entered homes, arrested believers, and tried to stop the movement before it spread.
                Saul believed he was defending God’s honor by opposing what he saw as a false and
                disruptive sect. <small><a href="https://ebible.org/study/?t1=local%3Aeng-web&w1=bible&v1=AC9_1"
                        title="Acts 9:1">
                        <ruby>Acts<rt>9:1</rt></ruby>
                    </a></small>
            </p>
            <p class="p_indent">
                In Jesus’ time, many people were waiting for a special king—a strong, conquering leader who would save
                them. Saul believed this too. So when he saw the followers of Jesus talking
                about a different kind of Savior, he felt worried. He thought they were changing things too quickly and
                might hurt the way his people worshiped God. Because he cared so much about
                protecting his faith, he tried to stop them. He wasn’t trying to be cruel — he just didn’t understand
                yet that Jesus was truly the Savior God had promised.
            </p>
