            <h3>The Rise of the Early Church</h3>
            <p>
                Following the resurrection of Jesus Christ and the outpouring of the Holy Spirit at
                <a href="https://en.wikipedia.org/wiki/Pentecost" title="Wikipedia Pentecost">Pentecost</a>,
                the early Christian movement grew rapidly in Jerusalem. Known initially as
                “<a href="https://www.gotquestions.org/the-Way.html" title="Got Questions: The Way">The Way</a>,”
                this vibrant assembly of believers was marked by apostolic teaching, fellowship, miracles,
                and bold proclamation of Christ’s resurrection
                <small><a href="https://ebible.org/study/?v1=AC2_42&w1=bible&t1=local%3Aeng-web"
                        title="Acts 2:42-47"><ruby>Acts<rt>2:42-47</rt></ruby></a></small>.
                As thousands of Jews embraced Jesus as the promised Messiah, the movement's explosive momentum stirred
                intense anxiety
                among Jerusalem’s religious authorities, creating the volatile environment in which Saul of Tarsus
                emerged.
            </p>

            <p class="p_indent"> After Jesus came back to life and went up to heaven, God sent the Holy Spirit to help
                His followers. Because of this, lots and lots of people in Jerusalem
                started believing in Jesus. They called themselves “The Way” because they wanted to follow the way Jesus
                taught them to live, also because
                <a href="https://ebible.org/study/?t1=local%3Aeng-web&w1=bible&v1=JN14_6" title="John 14:6">God is the
                    way</a>, the truth, and the life, and what a better way to start than to
                follow Him who is leading the way. So many people were joining them that the Jerusalem leaders became
                scared and upset.
                They didn’t understand what God was doing, and they worried that everything was changing too quickly.
                This is when Saul of Tarsus,
                the Pharisee, showed up, a man who thought he was protecting God by stopping the followers of Jesus.
                Saul, later known as Paul, didn’t know yet that Jesus really was the Savior God had promised.
            </p>
