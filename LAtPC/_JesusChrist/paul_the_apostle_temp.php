        <article>
            <h3>The Stoning of Stephen</h3>
            <p>
                Stephen, one of the first <a
                    href="https://saintpaulseminary.org/general/what-is-a-deacon-in-the-catholic-church/"
                    title="What is a deacon in the Catholic Church?">deacons</a>
                of the early church, boldly preached about Jesus
                and challenged the religious leaders of Jerusalem. His speech in
                <a href="https://ebible.org/study/?t1=local%3Aeng-web&w1=bible&v1=AC7_51" title="Acts 7:51">
                    <ruby>Acts<rt>7:51</rt></ruby>
                </a> angered the council, leading to his execution by stoning.
                <a href="https://ebible.org/study/?t1=local%3Aeng-web&w1=bible&v1=AC7_58" title="Acts 7:58">
                    <ruby>Acts<rt>7:58</rt></ruby>
                </a> notes that the witnesses laid their cloaks at Saul’s feet, showing he approved
                of the killing. Stephen became the first Christian martyr, and his death sparked
                a wave of persecution that scattered believers throughout Judea and beyond.
            </p>
            <article style="column-count:2; column-gap: 3em; column-rule: 1px solid #777;padding-bottom:1em;">
                <p class="p_indent">
                    Stephen loved Jesus so much that he wanted everyone to understand how special He is. When Stephen
                    talked
                    about God’s truth, some of the leaders didn’t want to listen. Their hearts were closed, almost like
                    doors that wouldn’t open, and that made them very angry. Even though Stephen was brave and kind,
                    they
                    hurt him, and a man named Saul stood nearby agreeing with them.
                </p>
                <p class="p_indent">
                    After Stephen died, many Christians felt scared and left Jerusalem to stay safe. But even though
                    they
                    had to move to new places, they didn’t stop sharing Jesus’ love for teaching. Everywhere they went,
                    they told people
                    about the good news, like tiny lights spreading across a dark room. God used their travels to help
                    even
                    more families learn about Jesus, turning something sad into something that brought hope to the
                    world.
